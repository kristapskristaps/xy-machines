"""Generate the instrument's fixed-point oscillator and control tables."""
import math
from pathlib import Path

root = Path(__file__).resolve().parent
tables = {
    'sine': ('opxy::i16', [round(32767 * math.sin(2 * math.pi * i / 512)) for i in range(513)]),
    'tuning': ('opxy::u32', [round(65536 * 2 ** (((i - 64) / (64 if i <= 64 else 63)))) for i in range(128)]),
    'decay': ('opxy::i32', [round(2147483647 * math.exp(math.log(0.001) / (max(4, 4 * i) * 44.1))) for i in range(1538)]),
    'tone': ('opxy::i32', [round(32767 * (1 - math.exp(-2 * math.pi * (1500 + 17000 * i / 127) / 44100))) for i in range(128)])
}
header = ['#pragma once', '#include <opxy/types.hpp>', 'namespace x0x { namespace tables {']
source = ['// Generated by dsp/generate_tables.py.', '#include "tables.h"', 'namespace x0x { namespace tables {']
for name, (kind, data) in tables.items():
    header.append(f'extern const {kind} {name}[{len(data)}];')
    source.append(f'const {kind} {name}[{len(data)}] = {{')
    source.extend('    ' + ','.join(map(str, data[i:i + 12])) + ',' for i in range(0, len(data), 12))
    source.append('};')
header.append('}}\n'); source.append('}}\n')
(root / 'tables.h').write_text('\n'.join(header))
(root / 'tables.cpp').write_text('\n'.join(source))
