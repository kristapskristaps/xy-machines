"""Generate Open303 TB_303 coefficients for Acidline's original cutoff range.
Approximation adapted via Acid Rain; see ../NOTICE.md for MIT attribution.
"""
from pathlib import Path
import math

def q31(x):
    return max(-2147483648,min(2147483647,round(x*2147483648)))

coefficients=[];feedback=[]
for i in range(65):
    frequency=35*400**(i/64)
    fx=frequency/(44100*math.sqrt(2))
    b0=(0.00045522346+6.1922189*fx)/(1+12.358354*fx+4.4156345*fx*fx)
    k=fx*(fx*(fx*(fx*(fx*(fx+7198.6997)-5837.7917)-476.47308)+614.95611)+213.87126)+16.998792
    coefficients.append(q31(2*b0));feedback.append(round(k*65536))
text='// Generated by tools/generate_ladder.py; Open303/Acid Rain MIT adaptation.\n#pragma once\n#include <opxy/types.hpp>\nnamespace acidline { namespace ladder_tables {\n'
for name,values in [('b0x2',coefficients),('feedback',feedback)]:
    text+='static const opxy::i32 '+name+'[65]={'+','.join(map(str,values))+'};\n'
text+='const opxy::i32 input_highpass='+str(q31(1-math.exp(-2*math.pi*44.486/44100)))+';\n'
text+='const opxy::i32 feedback_highpass='+str(q31(1-math.exp(-2*math.pi*150/44100)))+';\n}}\n'
(Path(__file__).resolve().parents[1]/'ladder_tables.h').write_text(text)
