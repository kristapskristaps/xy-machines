"""Generate original chip waveforms, mip levels and fixed-point control curves."""
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CAPS = [31, 15, 7, 3, 1]


def generate():
    phase = np.arange(8192) / 8192
    angle = phase * 2 * np.pi
    triangle = 2 / np.pi * np.arcsin(np.sin(angle))
    # Original 32-cell, four-bit wave ROM. No console samples or firmware.
    rom = []
    cells = np.arange(32) * 2 * np.pi / 32
    for values in [np.sin(cells) + .3 * np.sin(3 * cells),
                   np.sin(cells) + .45 * np.sin(2 * cells) + .2 * np.sin(4 * cells),
                   np.sin(cells) + .55 * np.sin(3 * cells) - .3 * np.sin(5 * cells),
                   np.sin(cells) + .5 * np.sin(5 * cells) + .25 * np.sin(7 * cells),
                   np.sin(cells) + .7 * np.sin(2 * cells) - .45 * np.sin(6 * cells)]:
        values = np.rint(values / np.max(np.abs(values)) * 7) / 7
        rom.append(values[(phase * 32).astype(int)])
    banks, drawings = [], []
    for family in range(4):
        frames, visual = [], []
        for color in np.linspace(0, 1, 9):
            if family == 0:
                wave = np.where(phase < .125 + color * .375, 1.0, -1.0)
            elif family == 1:
                wave = triangle + .4 * color * np.sin(3 * angle) + .22 * color**2 * np.sin(5 * angle)
            elif family == 2:
                position = color * 4
                at = min(3, int(position))
                wave = rom[at] * (1 - (position - at)) + rom[at + 1] * (position - at)
            else:
                position = color * 4
                at = min(3, int(position))
                t = (phase * 32).astype(np.uint32)
                a = ((t ^ (t >> (at + 1))) & 31) / 15.5 - 1
                b = ((t ^ (t >> (at + 2))) & 31) / 15.5 - 1
                wave = .65 * np.sin(angle) + .7 * (a + (b - a) * (position - at))
            wave -= wave.mean()
            spectrum = np.fft.rfft(wave)
            levels = []
            for cap in CAPS:
                reduced = np.zeros(129, dtype=complex)
                reduced[:cap + 1] = spectrum[:cap + 1] * 256 / len(wave)
                levels.append(np.fft.irfft(reduced, n=256))
            scale = min(.50 / np.sqrt(np.mean(levels[0]**2)), .83 / max(np.max(np.abs(v)) for v in levels))
            frames.append([np.rint(np.append(v, v[0]) * scale * 32768).astype(int).tolist() for v in levels])
            visual.append(np.rint(levels[0][::4] * scale * 32768).astype(int).tolist())
        banks.append(frames)
        drawings.append(visual)

    def array(name, values, kind='opxy::i32'):
        return f'static const {kind} {name}[] = {{' + ','.join(str(int(x)) for x in values) + '};\n'

    q = np.arange(129) / 128
    header = '// Generated by resources/generate_tables.py. Original waveforms.\n#pragma once\n#include <opxy/types.hpp>\nnamespace bitflip { namespace tables {\n'
    header += array('sine', np.rint(np.sin(np.arange(257) * 2 * np.pi / 256) * 32767), 'opxy::i16')
    controls = '// Generated control curves.\n#pragma once\n#include <opxy/types.hpp>\nnamespace bitflip { namespace tables {\n'
    controls += array('sweep', np.rint(4096 * 2**((q - .5) * 4)))
    controls += array('arp_rate', np.rint(np.array([8,12,16,24,32,40,64,80]) * 4294967296 / 44100))
    controls += array('clock', np.rint(np.array([1/32,1/16,1/8,1/5,1/4,1/3,1/2,1]) * 65536))
    controls += array('intervals', np.rint(4096 * 2**(np.arange(25) / 12)))
    controls += array('band_ends', [0x70000000 // h for h in CAPS], 'opxy::u32')
    (ROOT / 'control_tables.h').write_text(controls + '} }\n')
    header += 'static const opxy::i16 waves[4][9][5][257] = {\n'
    for frames in banks:
        header += ' {\n'
        for levels in frames:
            header += '  {\n' + ''.join('   {' + ','.join(map(str, row)) + '},\n' for row in levels) + '  },\n'
        header += ' },\n'
    header += '};\n} }\n'
    (ROOT / 'tables.h').write_text('#include \"control_tables.h\"\n' + header)
    drawing = '// Generated by resources/generate_tables.py. Illustrative waveforms only.\n#pragma once\n#include <opxy/types.hpp>\nnamespace bitflip { namespace visual {\nstatic const opxy::i16 waves[4][9][64] = {\n'
    for frames in drawings:
        drawing += ' {\n' + ''.join('  {' + ','.join(map(str, row)) + '},\n' for row in frames) + ' },\n'
    (ROOT / 'visual_tables.h').write_text(drawing + '};\n} }\n')


if __name__ == '__main__':
    generate()
