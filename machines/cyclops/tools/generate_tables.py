"""Reproduce Cyclops's integer DSP tables using Python's standard library."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def array(name, values, width=10):
    rows = ["    " + ", ".join(str(v) for v in values[i:i + width]) + ","
            for i in range(0, len(values), width)]
    return f"static const opxy::i32 {name}[{len(values)}] = {{\n" + "\n".join(rows) + "\n};\n"


def generate():
    text = "// Generated by tools/generate_tables.py; integer runtime, no external DSP dependencies.\n#pragma once\n#include <opxy/types.hpp>\nnamespace cyclops { namespace tables {\n"
    # Common scaling preserves level across mip levels. Square is the difference
    # between two half-cycle-separated saws, with the same fundamental level.
    for band in range(9):
        harmonics = 1 << band
        values = []
        for n in range(1024):
            phase = 2 * math.pi * n / 1024
            saw = -2 / math.pi * sum(math.sin(k * phase) / k for k in range(1, harmonics + 1))
            values.append(round(saw * 0.40 * (1 << 14)))
        values.append(values[0])
        text += array(f"saw_{band}", values)
        square = [values[n] - values[(n + 512) % 1024] for n in range(1024)]
        square.append(square[0])
        text += array(f"square_{band}", square)
    text += "static const opxy::i32* const saw[9] = {" + ", ".join(f"saw_{b}" for b in range(9)) + "};\n"
    text += "static const opxy::i32* const square[9] = {" + ", ".join(f"square_{b}" for b in range(9)) + "};\n"
    # 32 positions per octave. Last entry is interpolation padding.
    hz = [30 * 2 ** (i / 32) for i in range(292)]
    text += array("cutoff_hz", [round(f) for f in hz])
    text += array("pole", [round((lambda g: g / (1 + g))(math.tan(math.pi * f / 44100)) * 32767) for f in hz])
    text += array("log2_fraction", [round(math.log2(1 + i / 256) * 65536) for i in range(257)])
    text += array("tanh_q14", [round(math.tanh(i / 64) * (1 << 14)) for i in range(513)])
    text += array("detune_q20", [round(2 ** ((i * 50 / 128) / 1200) * (1 << 20)) for i in range(129)])
    text += "}}\n"
    (ROOT / "tables.h").write_text(text)


if __name__ == "__main__":
    generate()
