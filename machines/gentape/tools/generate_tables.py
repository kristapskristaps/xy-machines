"""Generate the Q27 tanh curve and four recorder profiles, without dependencies."""
from pathlib import Path
import math

MACHINE=Path(__file__).resolve().parents[1]

def main():
    values=[round(math.tanh((i-512)/128)*(1<<27)) for i in range(1025)]
    lines=['// Generated by tools/generate_tables.py; do not edit.','#pragma once','namespace gentape {','struct alignas(8) CurveSegment { opxy::i32 base, delta; };','alignas(32) const CurveSegment tanh_curve[1024] = {']
    lines+=['    '+', '.join('{'+str(values[i])+', '+str(values[i+1]-values[i])+'}' for i in range(start,start+4))+',' for start in range(0,1024,4)]
    lines+=['};','struct Model { opxy::i32 hp, lp, bump, gain; };','const Model models[4] = {']
    for hp,lp,bump,gain in [(0,None,.5,1),(110,5400,.575,1.05),(110,8500,.55,1.03),(230,1200,0,1.30)]:
        row=[round((1-math.exp(-2*math.pi*hp/44100))*2147483647),2147483647 if lp is None else round((1-math.exp(-2*math.pi*lp/44100))*2147483647),round(bump*2147483647),round(gain*(1<<27))]
        lines.append('    {'+', '.join(map(str,row))+'},')
    lines+=['};','}'];(MACHINE/'tables.h').write_text('\n'.join(lines)+'\n')

if __name__=='__main__':main()
