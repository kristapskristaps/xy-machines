"""Match four shorter FDN paths to the preceding plate's delay/decay scale."""
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DELAYS=(659,797,953,1151)
ORIGINAL=(249+1650+667+1378+337+1562+984+1172)/2

def generate():
 text='// Generated by tools/generate_fdn.py; Q15 feedback and damping.\n#pragma once\n#include <opxy/types.hpp>\nnamespace halo { namespace fdn_tables {\n'
 for name in ('decay','damping'):
  text+='static const opxy::i16 '+name+'[257][4]={\n'
  for i in range(257):
   value=i/256;row=[]
   for delay in DELAYS:
    if name=='decay':gain=value**(2*delay/ORIGINAL)
    else:
     high=value/(2-value);rooted=high**(delay/ORIGINAL)
     gain=2*rooted/(1+rooted)
    row.append(min(32767,round(gain*32768)))
   text+=' {'+','.join(map(str,row))+'},\n'
  text+='};\n'
 (ROOT/'fdn_tables.h').write_text(text+'}}\n')
if __name__=='__main__':generate()
