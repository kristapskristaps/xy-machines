"""Losslessly expand Arc's original tuning calibration outside audio callbacks."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

MACHINE = Path(__file__).resolve().parents[1]


def expanded():
    source = json.loads((MACHINE/'tools/gp_source.json').read_text())
    offsets, data = source['row_offsets'], source['compressed']
    if len(offsets) != 33 or any(not -128 <= value <= 127 for value in data):
        raise ValueError('Invalid compressed calibration data')
    rows = []
    for k, offset in enumerate(offsets):
        count = data[offset]
        if not 0 <= count <= 97:
            raise ValueError('Invalid row width')
        cursor, total, previous = offset + 1, 0, 0
        row = []
        for column in range(97):
            if column < count:
                delta = data[cursor]; cursor += 1
                above = rows[k-1][column] if k else 0
                if delta == -128:
                    delta = (data[cursor] & 255) + data[cursor+1]*256
                    cursor += 2
                total += delta + above - previous
                previous = above
            row.append(total & 65535)
        if cursor != (offsets[k+1] if k+1 < len(offsets) else len(data)):
            raise ValueError('Compressed row boundary differs')
        rows.append(row)
    binary = b''.join(struct.pack('<97H', *row) for row in rows)
    if hashlib.sha256(binary).hexdigest() != source['expanded_sha256']:
        raise ValueError('Expanded table differs from the original C++ decoder readout')
    return rows


def rendered(rows):
    lines = ['#pragma once', '// Losslessly expanded Hundekraft 3.0.3 Arc calibration; see NOTICE and LICENSE.',
             '// Generated by tools/generate_gp.py; do not edit.',
             'namespace hkarc { namespace port {',
             'static const unsigned short ARC_GP[33][97] = {']
    for row in rows:
        lines.append('    {')
        for start in range(0, len(row), 12):
            lines.append('        '+', '.join(map(str, row[start:start+12]))+',')
        lines.append('    },')
    return '\n'.join(lines+['};', '}}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = MACHINE/'gp_table.hpp'
    output = rendered(expanded())
    if args.check:
        if not path.is_file() or path.read_text() != output:
            raise SystemExit('FAIL: tuning table differs; run tools/generate_gp.py')
        print('PASS: 3,201 calibration values match the original decoder readout')
    else:
        path.write_text(output)


if __name__ == '__main__':
    main()
