typedef struct {
  uint32_t ph, hph;
  int32_t click;
  uint32_t noise;
  int32_t level[3];
} voice_t;

struct Dsp {
  const int32_t *pitch_input;
  uint8_t *scratch;
  uint8_t fx_page[3][4];
  op1_beat_t beat;
  int16_t meter;
  voice_t voices[1];
  uint32_t horn_ph, drum_ph;
  int32_t horn_speed, drum_speed;
  int last_voice;
  volatile uint32_t pew_blocks;
  volatile uint32_t pew_horn, pew_drum;
  volatile int16_t pew_knobs[4];
  void defaults() { last_voice = 1; }
  inline int16_t op1_sat16(int32_t x) {
    return x > 32767 ? 32767 : x < -32768 ? -32768 : (int16_t)x;
  }

  inline int32_t op1_mul16(int32_t a, int32_t b) { return (a * b) >> 15; }

  inline int32_t read(const int16_t *w, uint32_t ph) {
    const uint32_t i = ph >> 23;
    const int32_t f = (int32_t)((ph >> 8) & 0x7FFF);
    const int32_t a = w[i];
    return a + (((w[i + 1] - a) * f) >> 15);
  }

  inline int32_t rsin(uint32_t ph) { return pw_sin[ph >> 22]; }

  void engine_note_on(void *self, const int16_t *knobs) {
    voice_t *v = &voices[0];
    for (int k = 0; k < 3; k++)
      v->level[k] = knobs[k] < 0 ? 0 : knobs[k];
    v->ph = v->hph = 0;
    v->click = 32767;
    v->noise = 0x9E3779B9u ^ (uint32_t)(uintptr_t)self;
  }

  void engine_note_off(void *self, const int16_t *knobs) {
    (void)self;
    (void)knobs;
  }

  void engine_render(void *self, int16_t *out, const int16_t *knobs) {
    for (int i = 0; i < 4; i++)
      pew_knobs[i] = knobs[i];
    const int vi = 0;
    voice_t *v = &voices[vi];
    int vel = 127;
    if (vel < 1 || vel > 127)
      vel = 100;
    int32_t level[3], delta[3];
    for (int k = 0; k < 3; k++) {
      int32_t target = knobs[k] < 0 ? 0 : knobs[k];
      level[k] = v->level[k] * 128;
      delta[k] = target - v->level[k];
      v->level[k] = target;
    }
    if (vi <= last_voice) {
      const int32_t k3 = knobs[3] < 0 ? 0 : knobs[3];
      const int32_t target =
          8726000 + (int32_t)(((int64_t)k3 * 74800000) >> 15);
      horn_speed += (target - horn_speed) >> 6;
      drum_speed += ((target * 7 / 8) - drum_speed) >> 8;
      horn_ph += (uint32_t)horn_speed;
      drum_ph += (uint32_t)drum_speed;
      pew_horn = horn_ph;
      pew_drum = drum_ph;
    }
    last_voice = vi;
    const int32_t hs = rsin(horn_ph), hc = rsin(horn_ph + 0x40000000u),
                  ds = rsin(drum_ph);
    const int32_t horn_amp = 27852 + ((hs * 4915) >> 15);
    const int32_t drum_amp = 25395 + ((ds * 7372) >> 15);
    const int32_t click_lvl = knobs[2] < 0 ? 0 : knobs[2] >> 2;
    const int32_t gain = (30000 * vel) >> 7;
    uint32_t ph = v->ph, hph = v->hph;
    int32_t click = v->click;
    uint32_t noise = v->noise;
    for (int i = 0; i < 128; i++) {
      const uint32_t inc = pitch_input[i] >> 1;
      ph += inc;
      hph += inc + (uint32_t)(((int32_t)(inc >> 10) * hc) >> 15);
      const int32_t lo = (read(pw_low, ph) * (level[0] >> 7)) >> 15;
      const int32_t hi = ((read(pw_mid, hph) * (level[1] >> 7)) >> 15) +
                         ((read(pw_high, hph) * (level[2] >> 7)) >> 15);
      int32_t y = (lo * drum_amp + hi * horn_amp) >> 15;
      for (int k = 0; k < 3; k++)
        level[k] += delta[k];
      if (click > 64) {
        noise = noise * 1664525u + 1013904223u;
        y += (((int32_t)(noise >> 17) - 16384) * ((click * click_lvl) >> 15)) >>
             15;
        click -= click >> 5;
      }
      if (y > 24000)
        y = 24000 + ((y - 24000) >> 2);
      if (y < -24000)
        y = -24000 + ((y + 24000) >> 2);
      out[i] = op1_sat16((y * gain) >> 15);
    }
    v->ph = ph;
    v->hph = hph;
    v->click = click;
    v->noise = noise;
    pew_blocks++;
  }
};
