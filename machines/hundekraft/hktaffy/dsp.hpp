typedef struct {
  uint32_t ph;
  int32_t env;
  int32_t wave, dcw, resonance;
  int control_ready;
  int32_t dc_q10;
} voice_t;

typedef struct {
  int sa, sb;
  int32_t frac, d, inv1, inv2, rr, k3;
} setup_t;

struct Dsp {
  const int32_t *pitch_input;
  uint8_t *scratch;
  uint8_t fx_page[3][4];
  op1_beat_t beat;
  int16_t meter;
  voice_t voices[1];
  volatile uint32_t taffy_blocks;
  volatile int32_t taffy_dcw;
  volatile int32_t taffy_env;
  volatile int16_t taffy_knobs[4];
  void defaults() {}
  inline int16_t op1_sat16(int32_t x) {
    return x > 32767 ? 32767 : x < -32768 ? -32768 : (int16_t)x;
  }

  inline int32_t op1_mul16(int32_t a, int32_t b) { return (a * b) >> 15; }

  inline int32_t cosq(int32_t p) {
    p &= 0x7FFF;
    const int32_t i = p >> 5, f = (p & 31) << 10;
    const int32_t a = tf_cos[i];
    return a + (((tf_cos[i + 1] - a) * f) >> 15);
  }

  inline int32_t bend(int32_t x, int32_t d, int32_t inv1, int32_t inv2) {
    return x < d ? (x * inv1) >> 15 : 16384 + (((x - d) * inv2) >> 15);
  }

  inline int32_t shape(int s, int32_t x, int32_t d, int32_t inv1,
                       int32_t inv2) {
    switch (s) {
    case 0:
      return cosq(bend(x, d, inv1, inv2));
    case 1: {
      const int32_t h = x >> 14, xl = (x << 1) & 0x7FFF;
      const int32_t w = xl < 2 * d ? (xl * inv1) >> 16 : 16384;
      return cosq((h << 14) + w);
    }
    case 2: {
      return x < 2 * d ? cosq((x * inv1) >> 15) : 32767;
    }
    default:
      return x < 16384 ? cosq(bend(x << 1, d, inv1, inv2)) : 32767;
    }
  }

  inline void setup(setup_t *p, int32_t k0, int32_t dcw, int32_t k3) {
    p->d = 16384 - ((dcw * 15872) >> 15);
    p->inv1 = (16384 << 15) / p->d;
    p->inv2 = (16384 << 15) / (32768 - p->d);
    const int32_t pos = k0 * 3;
    p->sa = pos >> 15;
    p->sb = p->sa + (p->sa < 3);
    p->frac = pos & 0x7FFF;
    p->rr = 256 + ((dcw * 3840) >> 15);
    p->k3 = k3;
  }

  inline int32_t sample(const setup_t *p, int32_t x) {
    const int32_t a = shape(p->sa, x, p->d, p->inv1, p->inv2);
    int32_t y =
        a + (((shape(p->sb, x, p->d, p->inv1, p->inv2) - a) * p->frac) >> 15);
    const int32_t reso = (cosq(((x * p->rr) >> 8) - 8192) * (32767 - x)) >> 15;
    return y + (((reso - y) * p->k3) >> 15);
  }

  int32_t taffy_wave_at(int32_t k0, int32_t dcw, int32_t k3, int32_t x) {
    setup_t p;
    setup(&p, k0, dcw, k3);
    return sample(&p, x & 0x7FFF);
  }

  void engine_note_on(void *self, const int16_t *knobs) {
    voice_t *v = &voices[0];
    (void)knobs;
    v->control_ready = 0;
    v->ph = 0;
    v->dc_q10 = 0;
    v->env = 32767;
  }

  void engine_note_off(void *self, const int16_t *knobs) {
    (void)self;
    (void)knobs;
  }

  void engine_render(void *self, int16_t *out, const int16_t *knobs) {
    for (int i = 0; i < 4; i++)
      taffy_knobs[i] = knobs[i];
    const int vi = 0;
    voice_t *v = &voices[vi];
    int vel = 127;
    if (vel < 1 || vel > 127)
      vel = 100;
    const int32_t k0 = knobs[0] < 0 ? 0 : knobs[0];
    const int32_t k1 = knobs[1] < 0 ? 0 : knobs[1];
    const int32_t k2 = knobs[2] < 0 ? 0 : knobs[2];
    const int32_t k3 = knobs[3] < 0 ? 0 : knobs[3];
    int32_t dcw = k1 + ((k2 * v->env) >> 15);
    if (dcw > 32767)
      dcw = 32767;
    v->env -= v->env >> 6;
    setup_t p, previous = {0};
    setup(&p, k0, dcw, k3);
    int changing = v->control_ready &&
                   (v->wave != k0 || v->dcw != dcw || v->resonance != k3);
    if (changing)
      setup(&previous, v->wave, v->dcw, v->resonance);
    v->wave = k0;
    v->dcw = dcw;
    v->resonance = k3;
    v->control_ready = 1;
    const int32_t gain = (13000 * vel) >> 7;
    uint32_t ph = v->ph;
    int32_t dc_q10 = v->dc_q10;
    for (int i = 0; i < 128; i++) {
      ph += pitch_input[i];
      const int32_t x = (int32_t)(ph >> 17);
      int32_t y = sample(&p, x);
      if (changing) {
        const int32_t before = sample(&previous, x);
        y = before + (((y - before) * i) >> 7);
      }
      dc_q10 += (y * 1024 - dc_q10) >> 10;
      y -= dc_q10 >> 10;
      out[i] = op1_sat16((y * gain) >> 15);
    }
    v->ph = ph;
    v->dc_q10 = dc_q10;
    taffy_blocks++;
    taffy_dcw = dcw;
    taffy_env = v->env;
  }
};
