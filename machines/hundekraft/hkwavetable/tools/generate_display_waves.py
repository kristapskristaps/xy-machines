"""Generate Wavetable's exact 25 display samples from the canonical audio waves."""
import argparse
import hashlib
from pathlib import Path
import re
import struct

MACHINE = Path(__file__).resolve().parents[1]
REFERENCE_SHA256 = '13a3abf418a344e0609625be2eb35e36e33f92e64813297d3a59853d0de10f10'


def samples():
    source = (MACHINE/'dsp.hpp').read_text()
    match = re.search(r'static const int16_t wt_waves\[8\]\[256\s*\+\s*1\] = \{(.*?)\n\};', source, re.S)
    if match is None:
        raise ValueError('Cannot find the canonical eight audio waves')
    values = [int(value) for value in re.findall(r'-?\d+', match.group(1))]
    if len(values) != 8*257 or any(not -32768 <= value <= 32767 for value in values):
        raise ValueError('Unexpected canonical audio wave data')
    rows = []
    for wave in range(8):
        row = values[wave*257:(wave+1)*257]
        points = []
        for point in range(25):
            phase = point*178956970
            index, fraction = phase >> 24, (phase >> 9) & 32767
            points.append(row[index]+((row[index+1]-row[index])*fraction//32768))
        rows.append(points)
    binary = b''.join(struct.pack('<25h', *row) for row in rows)
    if hashlib.sha256(binary).hexdigest() != REFERENCE_SHA256:
        raise ValueError('Display samples differ from the original C++ readout')
    return rows


def rendered(rows):
    lines = ['#pragma once', '// Hundekraft 3.0.3 display samples; retained terms: NOTICE and LICENSE.',
             '// Generated by tools/generate_display_waves.py from the unchanged audio waves.',
             '#include <opxy/types.hpp>', 'namespace hkwavetable { namespace display_wave {',
             'static const opxy::i16 samples[8][25] = {']
    for row in rows:
        lines.append('    {'+', '.join(map(str, row))+'},')
    return '\n'.join(lines+['};', '}}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = rendered(samples()); path = MACHINE/'display_waves.hpp'
    if args.check:
        if not path.is_file() or path.read_text() != output:
            raise SystemExit('FAIL: regenerate display_waves.hpp')
        print('PASS: all 200 display samples match the original C++ readout')
    else:
        path.write_text(output)


if __name__ == '__main__':
    main()
