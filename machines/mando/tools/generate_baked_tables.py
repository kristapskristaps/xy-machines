"""Preblend half-mip waves and sample the original integer tanh interpolant."""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate():
 source=(ROOT/'tables.h').read_text()
 def values(name):
  match=re.search(r'\b'+re.escape(name)+r'\[\d+\]\s*=\s*\{([^}]+)\}',source)
  return [int(x) for x in match.group(1).split(',') if x.strip()]
 def array(name,points):
  return 'static const opxy::i16 '+name+'['+str(len(points))+']={\n'+''.join(' '+','.join(map(str,points[i:i+12]))+',\n' for i in range(0,len(points),12))+'};\n'
 text='// Generated by tools/generate_baked_tables.py from tables.h.\n#pragma once\n#include "tables.h"\nnamespace mando { namespace baked_tables {\n'
 for shape in ('saw','square'):
  for band in range(1,9):
   text+=array(shape+'_half_'+str(band),[(a+b)//2 for a,b in zip(values(shape+'_'+str(band)),values(shape+'_'+str(band-1)))])
  text+='static const opxy::i16* const '+shape+'[9][3]={\n'
  text+=' {tables::'+shape+'_0,tables::'+shape+'_0,tables::'+shape+'_0},\n'
  for band in range(1,9):text+=' {tables::'+shape+'_'+str(band)+','+shape+'_half_'+str(band)+',tables::'+shape+'_'+str(band-1)+'},\n'
  text+='};\n'
 knots=values('tanh_q14')
 def original(x):
  return 16384 if x>=131072 else knots[x>>8]+((knots[(x>>8)+1]-knots[x>>8])*(x&255)>>8)
 positions=list(range(0,32769,16))+list(range(32896,131073,128))
 text+=array('tanh',list(map(original,positions)))
 text+='}}\n'
 (ROOT/'baked_tables.h').write_text(text)
if __name__=='__main__':generate()
