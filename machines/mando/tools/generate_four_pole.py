"""Generate stable four-pole subtractive lowpass coefficients; no runtime floats."""
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate():
 text='// Generated by tools/generate_four_pole.py; b0 Q31,a1 Q30,a2 Q31 per section.\n#pragma once\n#include <opxy/types.hpp>\nnamespace mando { namespace four_pole_tables {\n'
 grid=[round((lambda t:t/(1+t))(math.tan(math.pi*30*2**(i/8)/44100))*32767) for i in range(74)]
 text+='static const opxy::i32 grid[74]={'+','.join(map(str,grid))+'};\nstatic const opxy::i32 coefficients[33][74][6]={\n'
 old_corner=math.sqrt(2**.25-1)
 for row in range(33):
  resonance=row/32
  scale=old_corner+(1-old_corner)*resonance
  gain=1/(1+1.6*resonance*resonance)
  text+=' {\n'
  for gword in grid:
   g=gword/32768;nominal=44100/math.pi*math.atan(g/(1-g))
   bright=max(0.,min(1.,(nominal-2500)/9500));bright=bright*bright*(3-2*bright)
   quality=(.541196100146197,1.306562964876377+12*resonance*resonance*(1-.9*bright))
   t=g/(1-g)*scale;words=[]
   for section,q in enumerate(quality):
    denominator=1+t/q+t*t
    coefficients=[t*t/denominator*(gain if section==0 else 1),2*(t*t-1)/denominator,(1-t/q+t*t)/denominator]
    words.extend(round(x*2**bits) for x,bits in zip(coefficients,(31,30,31)))
   if not all(-2**31<=x<2**31 for x in words):raise ValueError('Coefficient overflow')
   text+='  {'+','.join(map(str,words))+'},\n'
  text+=' },\n'
 text+='};\nstatic const opxy::i32 drive[514]={'+','.join(str(round((2+6/(1+((i/512*11025)/1200)**4))*256)) for i in range(514))+'};\n}}\n';(ROOT/'four_pole_tables.h').write_text(text)
if __name__=='__main__':generate()
