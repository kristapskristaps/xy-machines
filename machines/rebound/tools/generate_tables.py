"""Regenerate fixed-point coefficients from definition.json; --check verifies them."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    parameters = json.loads((ROOT / 'definition.json').read_text())['parameters']
    labels = {p['id']: p['mapping'].get('labels', []) for p in parameters}

    def frequency(label):
        if label == 'off':
            return 0
        return float(label[:-1]) * 1000 if label.endswith('k') else float(label)

    maximum = 2147483647
    feedback = [round(float(label) / 200 * maximum) for label in labels['feedback']]
    # Even with Highpass off, a 10 Hz DC blocker remains in the loop.
    highpass = [round((1 - math.exp(-2 * math.pi * max(frequency(label), 10) / 44100)) * maximum)
                for label in labels['highpass']]
    lowpass = [round((1 - math.exp(-2 * math.pi * frequency(label) / 44100)) * maximum)
               if label != 'off' else maximum for label in labels['lowpass']]
    text = '// Generated by tools/generate_tables.py from definition.json.\n#pragma once\n\nnamespace rebound { namespace tables {\n'
    for name, values in [('feedback_half', feedback), ('highpass', highpass), ('lowpass', lowpass)]:
        text += f'const opxy::i32 {name}[] = {{\n'
        for start in range(0, len(values), 8):
            text += '    ' + ', '.join(str(value) for value in values[start:start + 8]) + ',\n'
        text += '};\n'
    return text + '}}\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'tables.h'
    expected = render()
    if args.check:
        if path.read_text() != expected:
            raise SystemExit('Stale tables.h: run tools/generate_tables.py')
        print('PASS: coefficient tables match the displayed feedback gains and filter frequencies')
    else:
        path.write_text(expected)


if __name__ == '__main__':
    main()
