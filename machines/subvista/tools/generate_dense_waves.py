"""Densify the original Subvista interpolation for nearest-point runtime lookup."""
from pathlib import Path
from generate_slopes import waves,wave_slopes

MACHINE=Path(__file__).resolve().parents[1]

def generate():
    banks=[]
    for wave in waves():
        slopes=wave_slopes(wave)
        values=[]
        for index in range(512):
            values.extend((wave[index],wave[index]+slopes[index]*16384))
        values.append(values[0])
        banks.append(values)
    header='// Generated by tools/generate_dense_waves.py from unchanged tables.h samples.\n// Original samples alternate with exact original-interpolator midpoint samples.\n#pragma once\n#include <opxy/types.hpp>\nnamespace subvista { namespace tables {\nstatic const opxy::i32 dense[8][1025]={\n'
    for values in banks:
        header+='  {\n'
        header+='\n'.join('    '+','.join(map(str,values[i:i+12]))+',' for i in range(0,len(values),12))+'\n  },\n'
    return header+'};\n}}\n'

if __name__=='__main__':
    (MACHINE/'dense_waves.h').write_text(generate())
