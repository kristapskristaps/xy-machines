"""Generate exact interpolation data from Subvista's existing waves."""
from pathlib import Path
import re

MACHINE = Path(__file__).resolve().parents[1]


def waves():
    source = (MACHINE/'tables.h').read_text()
    match = re.search(r'saw\[8\]\[513\]\s*=\s*(\{.*?\});',source,re.S)
    if not match:
        raise ValueError('Expected the original eight guarded waves')
    values = list(map(int,re.findall(r'-?\d+',match.group(1))))
    if len(values)!=8*513:
        raise ValueError('Unexpected wavetable size')
    return [values[band*513:(band+1)*513] for band in range(8)]


def wave_slopes(wave):
    result = []
    for before,after in zip(wave,wave[1:]):
        difference = after-before
        slope = (1 if difference>=0 else -1)*(abs(difference)//32768)
        if not -32768<=slope<=32767:
            raise ValueError('An interpolation slope does not fit i16')
        result.append(slope)
    return result


def generate():
    rows = []
    for wave in waves():
        rows.append('{'+','.join(map(str,wave_slopes(wave)))+'}')
    return '''// Generated by tools/generate_slopes.py from the unchanged tables.h waves.
#pragma once
#include <opxy/types.hpp>
namespace subvista { namespace tables {
static const opxy::i16 slopes[8][512] = {
'''+',\n'.join(rows)+'\n};\n}}\n'


def generate_points():
    rows = []
    for wave in waves():
        points = ['{%d,%d}' % pair for pair in zip(wave,wave_slopes(wave))]
        rows.append('{\n'+',\n'.join(','.join(points[i:i+8]) for i in range(0,512,8))+'\n}')
    return '''// Generated by tools/generate_slopes.py from the unchanged tables.h waves.
#pragma once
#include <opxy/types.hpp>
namespace subvista { namespace tables {
struct WavePoint { opxy::i32 value, slope; };
static const WavePoint points[8][512] = {
'''+',\n'.join(rows)+'\n};\n}}\n'


if __name__=='__main__':
    (MACHINE/'wave_slopes.h').write_text(generate())
    (MACHINE/'wave_points.h').write_text(generate_points())
