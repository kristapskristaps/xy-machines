"""Build nearest1024 quarter-reflected Vader tables from original interpolation."""
from pathlib import Path
import re

MACHINE=Path(__file__).resolve().parents[1]

def generate():
    source=(MACHINE/'tables.hpp').read_text()
    rows=list(re.finditer(r'const opxy::i16 (wave_\d+)\[513\] = \{([^}]+)\};',source))
    if len(rows)!=162:raise ValueError('Expected162 unique original waves')
    output='// Generated by tools/generate_nearest_waves.py from unchanged tables.hpp.\n// Original samples and exact interpolation midpoints; independent half-cycle quarters.\n#pragma once\n#include <opxy/types.hpp>\nnamespace vader { namespace nearest {\n'
    for row in rows:
        name=row.group(1);values=list(map(int,row.group(2).split(',')))
        if len(values)!=513 or values[0]!=values[-1]:raise ValueError('Missing cyclic guard')
        dense=[]
        for before,after in zip(values,values[1:]):dense.extend((before,(before+after)//2))
        dense.append(dense[0])
        if any(dense[i]!=dense[512-i] or dense[512+i]!=dense[1024-i] for i in range(513)):
            raise ValueError('Wave does not have exact per-half quarter reflection')
        quarter=dense[:257]+dense[512:769]
        if any(not -32768<=x<=32767 for x in quarter):raise ValueError('Nearest sample exceeds signed16')
        output+='static const opxy::i16 '+name+'[514]={\n'
        output+='\n'.join('    '+','.join(map(str,quarter[i:i+16]))+',' for i in range(0,514,16))+'\n};\n'
    grid=re.search(r'const opxy::i16\* const waves\[4\]\[9\]\[6\] = \{(.*?)\n\};',source,re.S)
    if not grid:raise ValueError('Missing original wave grid')
    output+='static const opxy::i16* const waves[4][9][6]={' +grid.group(1)+'\n};\n}}\n'
    return output

if __name__=='__main__':
    (MACHINE/'nearest_waves.hpp').write_text(generate())
