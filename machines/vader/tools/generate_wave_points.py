"""Pack exact Vader waveform samples/slopes from the committed analytic tables."""
from pathlib import Path
import re

MACHINE=Path(__file__).resolve().parents[1]

def generate():
    source=(MACHINE/'tables.hpp').read_text()
    rows=list(re.finditer(r'const opxy::i16 (wave_\d+)\[513\] = \{([^}]+)\};',source))
    if len(rows)!=162:raise ValueError('Expected162 unique original waves')
    output='// Generated by tools/generate_wave_points.py from unchanged tables.hpp samples.\n#pragma once\n#include <opxy/types.hpp>\nnamespace vader { namespace packed {\n// Low signed16: original value; high signed16: exact adjacent difference.\n'
    for row in rows:
        name=row.group(1);values=list(map(int,row.group(2).split(',')))
        if len(values)!=513 or values[0]!=values[-1]:raise ValueError('Wave lacks cyclic guard')
        points=[]
        for value,following in zip(values,values[1:]):
            slope=following-value
            if not -32767<=value<=32767 or not -32767<=slope<=32767:raise ValueError('Point exceeds signed halves')
            points.append(((slope&65535)<<16)|(value&65535))
        output+='static const opxy::u32 '+name+'[512]={\n'
        output+='\n'.join('    '+','.join(f'0x{x:08x}u' for x in points[i:i+8])+',' for i in range(0,512,8))+'\n};\n'
    grid=re.search(r'const opxy::i16\* const waves\[4\]\[9\]\[6\] = \{(.*?)\n\};',source,re.S)
    if not grid:raise ValueError('Missing original wave pointer grid')
    output+='static const opxy::u32* const waves[4][9][6]={' +grid.group(1)+'\n};\n}}\n'
    return output

if __name__=='__main__':
    (MACHINE/'wave_points.hpp').write_text(generate())
