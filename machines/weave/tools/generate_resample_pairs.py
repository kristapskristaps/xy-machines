"""Pack the existing resampler coefficients without changing their values."""
from pathlib import Path
import re

MACHINE = Path(__file__).resolve().parents[1]


def generate():
    source = (MACHINE / 'resample.h').read_text()
    rows = [list(map(int, re.findall(r'-?\d+', row)))
            for row in re.findall(r'\{([^{}]+)\}', source)
            if len(re.findall(r'-?\d+', row)) == 24]
    if len(rows) != 147 or any(row[0] or row[-1] for row in rows):
        raise ValueError('Expected 147 original 24-tap phases with zero endpoints')
    packed = []
    for row in rows:
        words = [(row[i] & 65535) | ((row[i + 1] & 65535) << 16)
                 for i in range(1, 23, 2)]
        # Retain a 48-byte phase stride; the final word is not processed.
        packed.append('    {' + ','.join(f'0x{word:08x}u' for word in words + [0]) + '}')
    return '''// Generated by tools/generate_resample_pairs.py from the unchanged resample.h.
#pragma once
#include <opxy/types.hpp>
namespace weave {
static const opxy::u32 resample_pairs[147][12] = {
''' + ',\n'.join(packed) + '\n};\n}\n'


if __name__ == '__main__':
    (MACHINE / 'resample_packed.h').write_text(generate())
