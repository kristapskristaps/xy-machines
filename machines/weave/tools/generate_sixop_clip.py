"""Generate the bounded integer quotient seed for SixOp's original soft clip."""
from pathlib import Path


def ratio(magnitude):
    squared=(magnitude*magnitude)>>25
    return (((27<<23)+squared)<<3)//(((27<<23)+9*squared)>>13)


def main():
    values=[min(ratio(i<<16),65536)-1 for i in range(769)]
    values.append(values[-1])  # Full-scale endpoint guard, fraction zero.
    lines=['// Generated by tools/generate_sixop_clip.py from the original integer curve.',
           '// Copyright (c) 2026 Kristaps Dreija. MIT; see ../LICENSE.',
           '#pragma once','static const uint16_t sixop_clip_seed[770] = {']
    for i in range(0,len(values),12):lines.append('    '+', '.join(map(str,values[i:i+12]))+',')
    lines+=['};','''// For |sample|<=3 in Q24, the interpolated estimate differs from the
// original integer quotient by [-3,+2]. Exhaustive tests prove that domain.
// One product and bounded remainder corrections recover the exact quotient.
__attribute__((always_inline)) static inline uint32_t sixop_clip_ratio(
        uint32_t magnitude,uint32_t numerator,uint32_t divisor) {
    const uint32_t index=magnitude>>16;
    const int32_t first=sixop_clip_seed[index];
    const int16_t delta=static_cast<int16_t>(sixop_clip_seed[index+1]-first);
    const int16_t fraction=static_cast<int16_t>((magnitude&65535u)>>1);
    uint32_t quotient=static_cast<uint32_t>(first+1+(delta*fraction>>15));
    uint32_t product=quotient*divisor;
    if(product>numerator) {
        --quotient;product-=divisor;
        if(product>numerator)--quotient;
    } else {
        uint32_t remainder=numerator-product;
        if(remainder>=divisor) {
            ++quotient;remainder-=divisor;
            if(remainder>=divisor) {
                ++quotient;remainder-=divisor;
                if(remainder>=divisor)++quotient;
            }
        }
    }
    return quotient;
}''','']
    target=Path(__file__).resolve().parents[1]/'vendor/macro_sixop_clip.h'
    target.write_text('\n'.join(lines))


if __name__=='__main__':main()
