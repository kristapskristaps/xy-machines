"""Project the folding transfer into compact, band-limitable harmonic frames."""
from pathlib import Path
import re
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def generate():
    source = (ROOT / 'vendor/braids_fold.h').read_text()
    transfer = np.array([int(v) for v in re.search(
        r'braids_fold\[\] = \{(.*?)\};', source, re.S)[1].split(',') if v.strip()]) / 32768
    phase = np.arange(16384) * (2 * np.pi / 16384)
    triangle = 2 / np.pi * np.arcsin(np.sin(phase))
    families = [[], []]
    for level in range(17):
        drive = .042 + .90 * (level / 16) ** 1.35
        odd = np.interp((triangle * drive + 1) * 128, np.arange(257), transfer)
        spectrum = np.fft.rfft(odd)
        spectrum[::2] = 0
        odd = np.fft.irfft(spectrum, n=len(phase)) + .12 * np.sin(phase)
        even = np.abs(odd)
        even -= even.mean()
        for family, wave in enumerate([odd, even]):
            spectrum = np.fft.rfft(wave) * 2 / len(phase)
            coefficients = []
            for harmonic in range(1, 10):
                # T_n(sin phase) alternates sine signs for odd n and cosine signs for even n.
                sign = -1 if harmonic % 4 in (2, 3) else 1
                coefficient = -spectrum[harmonic].imag if harmonic % 2 else spectrum[harmonic].real
                coefficients.append(coefficient * sign)
            coefficients = np.array(coefficients)
            coefficients *= .90 / max(np.abs(coefficients).sum(), 1e-12)
            families[family].append(np.rint(coefficients * 32768).astype(int).tolist())
    clean = np.array([1 / n**2 if n % 2 else 0 for n in range(1, 10)])
    clean *= .90 / clean.sum()
    header = ('// Generated by resources/generate_coast.py.\n'
              '// Braids transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n'
              '#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace coast {\n')
    header += 'static const opxy::i16 clean[9] = {' + ','.join(map(str, np.rint(clean * 32768).astype(int))) + '};\n'
    header += 'static const opxy::i16 frames[2][17][9] = {\n'
    for family in families:
        header += '  {\n' + ''.join('    {' + ','.join(map(str, row)) + '},\n' for row in family) + '  },\n'
    header += '};\n} }\n'
    (ROOT / 'coast_tables.h').write_text(header)


if __name__ == '__main__':
    generate()
