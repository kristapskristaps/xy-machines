"""Densify the original integer interpolant, not a new folding curve."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
source=(root/'tables.h').read_text()
body=re.search(r'waves\[8\]\[17\]\[513\] = \{(.*?)\};',source,re.S)[1]
rows=re.findall(r'\{([^{}]+)\}',body)
if len(rows)!=136:raise RuntimeError('Unexpected original wave count')
text='// Generated by resources/generate_dense_points.py from original tables.h.\n// Folding transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace dense {\nstatic const opxy::i16 waves[8][17][1025]={\n'
for b in range(8):
 text+=' {\n'
 for f in range(17):
  old=[int(x) for x in rows[b*17+f].split(',') if x.strip()]
  if len(old)!=513:raise RuntimeError('Unexpected wave length')
  values=[]
  for i in range(512):values.extend([old[i],old[i]+((old[i+1]-old[i])>>1)])
  values.append(values[0])
  text+='  {'+','.join(map(str,values))+'},\n'
 text+=' },\n'
text+='};\n}}\n'
(root/'dense_points.h').write_text(text)
