"""Rebuild the fixed-point, band-limited Westfold tables. Requires NumPy."""
from pathlib import Path
import hashlib
import json
import re
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/braids_fold.h"


def generate():
    transfer = np.array([int(x) for x in re.search(
        r"braids_fold\[\] = \{(.*?)\};", SOURCE.read_text(), re.S)[1].split(",") if x.strip()]) / 32768.0
    phase = np.arange(16384) * (2 * np.pi / 16384)
    triangle = 2 / np.pi * np.arcsin(np.sin(phase))
    banks = [[] for _ in range(8)]
    spectra = []
    for index in range(17):
        drive = 0.042 + 0.90 * (index / 16) ** 1.35
        raw = np.interp((triangle * drive + 1) * 128, np.arange(257), transfer)
        spectrum = np.fft.rfft(raw)
        spectrum[::2] = 0
        raw = np.fft.irfft(spectrum, n=len(phase)) + 0.12 * np.sin(phase)
        raw *= min(0.48 / np.sqrt(np.mean(raw ** 2)), 0.88 / np.max(np.abs(raw)))
        spectrum = np.fft.rfft(raw)
        spectra.append(np.rint(np.minimum(1, np.abs(spectrum[:33]) * 2 / len(phase)) * 32767).astype(int))
        for band in range(8):
            cap = 128 >> band
            reduced = np.zeros(257, dtype=complex)
            reduced[:cap + 1] = spectrum[:cap + 1] * 512 / len(phase)
            wave = np.fft.irfft(reduced, n=512)
            if np.max(np.abs(wave)) > 0.94:
                wave *= 0.94 / np.max(np.abs(wave))
            values = np.rint(wave * 32767).astype(int)
            banks[band].append(np.append(values, values[0]).tolist())
    q = np.arange(129) / 128
    durations = 0.045 * (8 / 0.045) ** q
    decay = np.rint(np.exp(-np.log(100) * 64 / (44100 * durations)) * 2147483647).astype(int)
    rates = np.rint(0.05 * (400 / 0.05) ** q / 44100 * 4294967296).astype(int)
    anchors = np.array([0.5, 1, 1.5, 2, 3, 4, 6, 8])
    ratio = np.rint(np.interp(q * 7, np.arange(8), anchors) * 4096).astype(int)
    cutoff = 55 + 17500 * q ** 1.9
    coefficients = np.rint((1 - np.exp(-2 * np.pi * cutoff / 44100)) * 32768).astype(int)
    sine = np.rint(np.sin(np.arange(513) * 2 * np.pi / 512) * 32767).astype(int)

    def array(name, values, ctype="opxy::i32"):
        vals = [str(int(x)) for x in values]
        rows = [", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16)]
        return f"static const {ctype} {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

    content = ("// Generated by resources/generate_tables.py. Do not edit.\n"
               "// Folding transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n"
               "#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace tables {\n")
    for name, values, ctype in [("sine", sine, "opxy::i16"), ("decay", decay, "opxy::i32"),
                                ("durations_ms", np.rint(durations * 1000).astype(int), "opxy::i32"),
                                ("visual_decay", np.rint(np.exp(-np.arange(256) * np.log(100) / 128) * 1024).astype(int), "opxy::i32"),
                                ("visual_spectrum", np.rint(np.sqrt(q) * 1900).astype(int), "opxy::i32"),
                                ("rates", rates, "opxy::i32"), ("ratios", ratio, "opxy::i32"),
                                ("gate_coefficients", coefficients, "opxy::i32")]:
        content += array(name, values, ctype)
    content += "static const opxy::i16 waves[8][17][513] = {\n"
    for bank in banks:
        content += "  {\n"
        for values in bank:
            content += "    {" + ",".join(map(str, values)) + "},\n"
        content += "  },\n"
    content += "};\nstatic const opxy::i16 spectrum[17][33] = {\n"
    for row in spectra:
        content += "    {" + ",".join(map(str, row)) + "},\n"
    content += "};\n} }\n"
    # The display always uses band 1, without a crossfade. Keep only that bank
    # in its self-contained translation unit instead of duplicating all eight.
    drawing = ("// Generated by resources/generate_tables.py. Display bank 1 only.\n"
               "// Folding transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n"
               "#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace draw_tables {\n")
    names = {"sine", "durations_ms", "visual_decay", "visual_spectrum", "rates", "ratios", "spectrum"}
    for match in re.finditer(r"static const opxy::i(?:16|32) ([a-z_]+)(?:\[\d*\])+ = \{.*?\};", content, re.S):
        if match[1] in names:
            drawing += match[0] + "\n"
    drawing += "static const opxy::i16 waves[17][513] = {\n"
    for values in banks[1]:
        drawing += "    {" + ",".join(map(str, values)) + "},\n"
    drawing += "};\n} }\n"
    (ROOT / "display_tables.h").write_text(drawing)
    (ROOT / "tables.h").write_text(content)
    print(json.dumps({"tables_bytes": 8 * 17 * 513 * 2,
                      "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                      "tables_sha256": hashlib.sha256(content.encode()).hexdigest(),
                      "display_tables_sha256": hashlib.sha256(drawing.encode()).hexdigest()}, indent=2))


if __name__ == "__main__":
    generate()
