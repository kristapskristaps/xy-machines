"""Retain the exact first half-cycle of the committed Westfold waves."""
from pathlib import Path
import re

MACHINE=Path(__file__).resolve().parents[1]

def arrays(name,shape,source):
    match=re.search(rf"{name}{shape} = \{{(.*?)\n\}};",source,re.S)
    if not match:raise ValueError('Missing original '+name)
    return list(map(int,re.findall(r'-?\d+',match.group(1))))

def half(wave):
    if len(wave)!=513 or wave[512]!=wave[0]:raise ValueError('Missing cyclic guard')
    if any(wave[i+256]!=-wave[i] for i in range(257)):raise ValueError('Wave is not exactly antisymmetric')
    if any(not -32767<=x<=32767 for x in wave):raise ValueError('Endpoint negation would overflow')
    return wave[:257]

def rows(values):
    return '\n'.join('    '+','.join(map(str,values[i:i+16]))+',' for i in range(0,len(values),16))

def generate():
    source=(MACHINE/'tables.h').read_text()
    sine=arrays('sine',r'\[\]',source)
    waves=arrays('waves',r'\[8\]\[17\]\[513\]',source)
    if len(waves)!=8*17*513:raise ValueError('Unexpected wave dimensions')
    header='// Generated by tools/generate_half_waves.py from unchanged tables.h samples.\n// Folding transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace half_tables {\nstatic const opxy::i16 sine[257]={\n'
    header+=rows(half(sine))+'\n};\nstatic const opxy::i16 waves[8][17][257]={\n'
    for bank in range(8):
        header+='  {\n'
        for fold in range(17):
            offset=(bank*17+fold)*513
            header+='    {\n'+rows(half(waves[offset:offset+513]))+'\n    },\n'
        header+='  },\n'
    return header+'};\n}}\n'

if __name__=='__main__':
    (MACHINE/'half_waves.h').write_text(generate())
