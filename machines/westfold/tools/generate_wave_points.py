"""Pack exact half-cycle values/slopes from the committed Westfold tables."""
from pathlib import Path
import re

MACHINE=Path(__file__).resolve().parents[1]

def arrays(name,shape,source):
    expression=rf"{name}{shape} = \{{(.*?)\n\}};"
    match=re.search(expression,source,re.S)
    if not match:raise ValueError('Missing original '+name)
    return list(map(int,re.findall(r'-?\d+',match.group(1))))

def packed(wave,guard=False):
    if len(wave)!=513 or wave[512]!=wave[0]:raise ValueError('Missing cyclic guard')
    if any(wave[i+256]!=-wave[i] for i in range(257)):raise ValueError('Wave is not exactly antisymmetric')
    result=[]
    count=257 if guard else 256
    for value,following in zip(wave[:count],wave[1:count+1]):
        slope=following-value
        if not -32767<=value<=32767 or not -32767<=slope<=32767:raise ValueError('Point does not fit signed halves')
        result.append(((slope&65535)<<16)|(value&65535))
    return result

def rows(words):
    return '\n'.join('    '+','.join(f'0x{x:08x}u' for x in words[i:i+8])+',' for i in range(0,len(words),8))

def generate():
    source=(MACHINE/'tables.h').read_text()
    sine=arrays('sine',r'\[\]',source)
    waves=arrays('waves',r'\[8\]\[17\]\[513\]',source)
    if len(waves)!=8*17*513:raise ValueError('Unexpected wave dimensions')
    header='// Generated by tools/generate_wave_points.py from unchanged tables.h samples.\n// Folding transfer: Copyright 2012 Emilie Gillet, MIT; see vendor/LICENSE.\n#pragma once\n#include <opxy/types.hpp>\nnamespace westfold { namespace points {\n// Low signed16 value; high signed16 slope. Wave rows include a half-cycle guard.\nstatic const opxy::u32 sine[256]={\n'
    header+=rows(packed(sine))+'\n};\nstatic const opxy::u32 waves[8][17][257]={\n'
    for bank in range(8):
        header+='  {\n'
        for fold in range(17):
            offset=(bank*17+fold)*513
            header+='    {\n'+rows(packed(waves[offset:offset+513],guard=True))+'\n    },\n'
        header+='  },\n'
    return header+'};\n}}\n'

if __name__=='__main__':
    (MACHINE/'wave_points.h').write_text(generate())
