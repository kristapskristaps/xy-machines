"""Rebuild compact PCM data from the credited recordings (requires ffmpeg).

Downloaded source audio stays in the supplied external cache. No download or
decode work happens in the instrument, its audio callback, or its normal build.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REV = "475cc3314fe06f6d1af02e9790ad9707c1f2b26b"
BASE = f"https://raw.githubusercontent.com/fluid-music/open-drums/{REV}/tr-707/TR707WAV/"
SOURCES = [(name, BASE + filename, 22050, "Public domain") for name, filename in (
    ("kick_a", "BassDrum1.wav"), ("kick_b", "BassDrum2.wav"),
    ("snare_a", "Snare1.wav"), ("snare_b", "Snare2.wav"),
    ("tom_low", "LowTom.wav"), ("tom_mid", "MedTom.wav"), ("tom_high", "HiTom.wav"),
    ("closed_hat", "HhC.wav"), ("open_hat", "HhO.wav"), ("crash", "Crash.wav"),
    ("ride", "Ride.wav"), ("cowbell", "CowBell.wav"), ("clap", "HandClap.wav"),
    ("rim", "RimShot.wav"), ("tambourine", "Tamb.wav"))]
SOURCES += [(name, f"https://cdn.freesound.org/previews/26/{ident}_19852-hq.mp3", 30000, "CC-BY-4.0")
            for name, ident in (("closed_909", 26532), ("open_909", 26650),
                                ("crash_909", 26568), ("ride_909", 26664))]


def fetch(item, cache, expected):
    name, url, rate, licence = item
    path = cache / (name + Path(url).suffix)
    if not path.exists():
        path.write_bytes(urllib.request.urlopen(url).read())
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if name in expected and digest != expected[name]:
        raise ValueError(f"Source hash changed for {name}; inspect the source rather than accepting changed audio")
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(rate),
                                   "-f", "f32le", "-"])
    samples = list(struct.unpack("<" + "f" * (len(raw) // 4), raw))
    peak = max(abs(x) for x in samples)
    if not peak:
        raise ValueError(f"Silent source: {name}")
    first = next(i for i, x in enumerate(samples) if abs(x) > peak * 0.001)
    last = len(samples) - next(i for i, x in enumerate(reversed(samples)) if abs(x) > peak * 0.0001)
    samples = samples[max(0, first - 4):min(len(samples), last + 64)]
    samples = [x * 0.85 / peak for x in samples]
    for i in range(min(32, len(samples))):
        samples[-i - 1] *= i / 32
    codes = [max(1, min(255, round(math.copysign(math.log1p(255 * abs(x)) / math.log(256), x) * 127) + 128))
             for x in samples]
    meta = dict(name=name, url=url, source_sha256=digest, licence=licence, rate=rate, frames=len(codes),
                encoded_sha256=hashlib.sha256(bytes(codes)).hexdigest())
    if licence == 'CC-BY-4.0':
        identifier = Path(url).name.split('_')[0]
        meta.update(source_page=f'https://freesound.org/people/altemark/sounds/{identifier}/',
                    attribution='Recorded by Janne G:son Berg (2005); edited/published by altemark',
                    licence_url='https://creativecommons.org/licenses/by/4.0/')
    return codes, meta


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", required=True, type=Path)
    args = parser.parse_args()
    cache = args.cache.resolve()
    if cache == ROOT or ROOT in cache.parents:
        parser.error("Keep downloaded audio outside the source repository")
    cache.mkdir(parents=True, exist_ok=True)
    provenance = ROOT / 'assets/provenance.json'
    expected = {entry['name']: entry['source_sha256'] for entry in json.loads(provenance.read_text())} if provenance.exists() else {}
    with ThreadPoolExecutor(max_workers=6) as pool:
        data = list(pool.map(lambda source: fetch(source, cache, expected), SOURCES))
    output = ['// Generated by assets/generate.py; recording credits in assets/CREDITS.md.',
              '#include "pcm.h"', 'namespace x0x { namespace pcm {']
    for codes, meta in data:
        output.append('static const opxy::u8 ' + meta['name'] + '[] = {')
        output.extend('    ' + ','.join(map(str, codes[i:i + 32])) + ',' for i in range(0, len(codes), 32))
        output.append('};')
    output.append('const Sample samples[sample_count] = {')
    output.extend('    {%s, %du, %du},' % (meta['name'], meta['frames'], meta['rate']) for _, meta in data)
    output.append('};')
    output.append('const opxy::i16 decode[256] = {')
    decoded = [round(math.copysign((256 ** (min(127, abs(i - 128)) / 127) - 1) / 255, i - 128) * 32767)
               for i in range(256)]
    output.extend('    ' + ','.join(map(str, decoded[i:i + 16])) + ',' for i in range(0, 256, 16))
    output.append('};\n}}\n')
    (ROOT / 'dsp/sample_data.cpp').write_text('\n'.join(output))
    (ROOT / 'assets/provenance.json').write_text(json.dumps([meta for _, meta in data], indent=2) + '\n')
    print(f"Generated {len(data)} recordings, {sum(len(codes) for codes, _ in data):,} encoded bytes")


if __name__ == '__main__':
    main()
