"""Generate Q14 spectral approximations for the 808 rectangular-wave cluster.

Filter centres follow Werner, Abel & Smith, ICMC/SMC 2014, sections 4 and 9.
These second-order sections approximate the spectral roles, not the complete
analogue circuits. Coefficients use the bilinear-transform biquad equations.
"""
import math
from pathlib import Path

filters = [('low_band', 'bp', 3440, 1.5), ('high_band', 'bp', 7100, 2),
           ('low_cut', 'hp', 1800, math.sqrt(.5)),
           ('hat_cut', 'hp', 5500, math.sqrt(.5)), ('air_cut', 'hp', 10500, 1)]
lines = ['// Generated by dsp/generate_metallic.py; 44,100 Hz, Q14.',
         '#pragma once', 'namespace x0x { namespace dsp {',
         'struct MetalCoefficients { opxy::i32 b0, b1, b2, a1, a2; };']
for name, kind, hz, q in filters:
    w = 2 * math.pi * hz / 44100
    c, a = math.cos(w), math.sin(w) / (2 * q)
    b = [a, 0, -a] if kind == 'bp' else [(1+c)/2, -(1+c), (1+c)/2]
    values = [round(v / (1+a) * 16384) for v in [*b, -2*c, 1-a]]
    if max(map(abs, values)) > 32768:
        raise ValueError('Q14 coefficient exceeds the signed 32-bit product bound')
    lines.append('static const MetalCoefficients ' + name + ' = {' + ','.join(map(str, values)) + '};')
lines.append('}}')
Path(__file__).with_name('metallic_coefficients.h').write_text('\n'.join(lines) + '\n')
