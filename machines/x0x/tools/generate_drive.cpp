// Host-only generator for the existing seven-bit cubic Drive control.
#include "../dsp/primitives.h"
#include <cstdio>
int main(){
    std::puts("// Generated by tools/generate_drive.cpp; original X0X cubic transfer.\n#include \"drive_curves.h\"\nnamespace x0x { namespace tables {\nconst opxy::i16 drive_curves[128][129]={");
    for(unsigned amount=0;amount<128;++amount){
        std::puts("{");
        for(unsigned point=0;point<=128;++point){
            const int sample=point==128?32767:int(point*256);
            const int value=x0x::dsp::drive(sample,amount);
            std::printf("%d%s%s",value,point==128?"":",",point%24==23?"\n":"");
        }
        std::puts("},");
    }
    std::puts("};\n}}");
}
