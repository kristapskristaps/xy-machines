// Host-only generator. Original X0X rectangular cluster and five filters are
// rendered into periodic source branches; no recordings or stock data are used.
#include "../dsp/metallic.h"
#include <cstdio>
#include <vector>
int main(){
    using namespace x0x::dsp;
    const u32 frames=22050,nominal[6]={2053,3696,3044,5227,5400,8000};
    const u32 initial[6]={0x183bc91du,0x9c3f742bu,0x5328ad49u,0xd74c1637u,0x328da561u,0xade78353u};
    std::puts("// Generated by tools/generate_stems.cpp from the X0X synth; 44.1 kHz.\n#include \"metal_stems.h\"\nnamespace x0x { namespace tables {");
    std::puts("const opxy::i16 metal_stems[3][3][22051]={");
    for(u32 anchor=0;anchor<3;++anchor){
        MetalState state={};std::vector<i32> stems[3];u32 frequency[6];
        const i32 character=anchor==0?0:anchor==1?64:127;
        for(u32 i=0;i<6;++i){const i32 detune=(character-64)*i32(i)/8;frequency[i]=u32((i32(nominal[i])+10*detune+10)/20);}
        for(auto& stem:stems)stem.resize(frames+1);
        for(u32 n=0;n<frames*6;++n){
            i32 cluster=0;
            for(u32 i=0;i<6;++i){
                const u32 phase=initial[i]+u32((static_cast<unsigned long long>(n%frames)*frequency[i]<<32)/frames);
                const u32 increment=u32((static_cast<unsigned long long>(frequency[i])<<32)/frames);
                cluster+=divide_signal<6>(metal_pulse(phase,increment,0x7fffffffu/(increment>>16)));
            }
            const i32 high=metal_filter(state.filters[1],high_band,cluster);
            const i32 bright=metal_filter(state.filters[3],hat_cut,high);
            const i32 air=metal_filter(state.filters[4],air_cut,high);
            state.air_low+=multiply(air-state.air_low,25432);
            const i32 bell=metal_filter(state.filters[2],low_cut,metal_filter(state.filters[0],low_band,cluster));
            if(n>=frames*5){stems[0][n%frames]=bell;stems[1][n%frames]=bright;stems[2][n%frames]=air-state.air_low;}
        }
        std::puts("{");
        for(auto& stem:stems){long long sum=0;for(u32 n=0;n<frames;++n)sum+=stem[n];const i32 dc=i32(sum/frames);for(u32 n=0;n<frames;++n)stem[n]-=dc;stem[frames]=stem[0];std::puts("{");for(u32 n=0;n<=frames;++n){if(stem[n]<-32768||stem[n]>32767)return 1;std::printf("%d%s%s",stem[n],n==frames?"":",",n%24==23?"\n":"");}std::puts("},");}
        std::puts("},");
    }
    std::puts("};\nconst opxy::i16 metallic_square[2][1025]={");
    for(u32 shape=0;shape<2;++shape){std::puts("{");for(u32 i=0;i<=1024;++i){const i32 partials=square_partials(i<<22);const i32 value=shape?divide_signal<138>(partials):divide_signal<23>(partials);std::printf("%d%s%s",value,i==1024?"":",",i%24==23?"\n":"");}std::puts("},");}
    std::puts("};\n}}");
}
