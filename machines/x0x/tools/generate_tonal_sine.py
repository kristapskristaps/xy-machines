"""Generate a 2048-point rounded sine for the drum oscillators."""
import math
from pathlib import Path
values = [round(math.sin(2 * math.pi * i / 2048) * 32767) for i in range(2048)]
text = "// Generated by tools/generate_tonal_sine.py. MIT; see ../LICENSE.\n#pragma once\nnamespace x0x { namespace dsp {\nstatic const opxy::i16 tonal_sine[2048]={\n"
text += "".join("    " + ",".join(map(str, values[i:i + 12])) + ",\n" for i in range(0, 2048, 12))
text += "};\n}}\n"
Path(__file__).resolve().parents[1].joinpath("dsp", "tonal_sine.h").write_text(text)
