"""Generate machine-owned fixed-point response tables; no runtime floating point."""
import math
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def array(name,kind,values):
 lines=[f'static const {kind} {name}[{len(values)}] = {{']
 for at in range(0,len(values),8):lines.append('    '+', '.join(map(str,values[at:at+8]))+',')
 return '\n'.join(lines+['};'])
sine=[round(math.sin(2*math.pi*i/256)*32767) for i in range(257)]
window=[round((.5-.5*math.cos(2*math.pi*i/256))*32767) for i in range(257)]
tone=[round((1-math.exp(-2*math.pi*(550*(4000/550)**(i/256))/11025))*32767) for i in range(257)]
soft=[round(math.tanh(i/256)*16777216) for i in range(1025)]
h=[]
for i in range(31):
 x=i-15
 v=.5 if x==0 else math.sin(math.pi*x/2)/(math.pi*x)
 w=.42-.5*math.cos(2*math.pi*i/30)+.08*math.cos(4*math.pi*i/30)
 h.append(v*w)
scale=.5/sum(h[::2])
h=[(v*scale if i%2==0 else .5 if i==15 else 0) for i,v in enumerate(h)]
fir=[round(v*2147483648) for v in h]
delta=1073741824-sum(fir[::2]);fir[14]+=delta//2;fir[16]+=delta-delta//2
text='// Generated by tools/generate_tables.py. Q15 controls, Q24 soft clip, Q31 halfband.\n#pragma once\n#include <opxy/types.hpp>\nnamespace halo { namespace tables {\n'
for name,kind,values in [('sine','opxy::i32',sine),('window','opxy::i32',window),('tone','opxy::i32',tone),('soft','opxy::i32',soft),('halfband','opxy::i32',fir)]:text+=array(name,kind,values)+'\n'
(root/'tables.h').write_text(text+'}}\n')
