"""Generate original analytic band-limited banks; requires NumPy."""
from pathlib import Path
import numpy as np

root = Path(__file__).resolve().parents[1]
phase = np.arange(8192) * (2 * np.pi / 8192)
sine = np.sin(phase)
banks = []
for mode in range(4):
    levels = []
    for level in range(9):
        drive = level / 8
        gain = 1 + 12 * drive
        if level == 0:
            signal = sine.copy()
        elif mode == 0:
            signal = np.tanh(gain * sine)
        elif mode == 1:
            signal = np.tanh(gain * (sine + 0.35 * drive))
        elif mode == 2:
            signal = np.arctan(gain * sine) + drive * 0.28 * np.cos(2 * phase)
        else:
            signal = np.sin((1 + 5 * drive) * sine)
        signal -= signal.mean()
        spectrum = np.fft.rfft(signal) / len(signal)
        # Positive fundamentals keep the clean branch in phase in every mode.
        spectrum[1] = -1j * max(abs(spectrum[1]), 0.30)
        normalization = max(1, np.max(np.abs(np.fft.irfft(spectrum, n=8192) * 8192)))
        bands = []
        for harmonics in (1, 3, 7, 15, 31):
            limited = spectrum.copy()
            limited[harmonics + 1:] = 0
            wave = np.fft.irfft(limited, n=8192) * 8192 / normalization
            bands.append(np.rint(np.r_[wave[::16], wave[0]] * 23000).astype(int))
        levels.append(bands)
    banks.append(levels)
peak = max(abs(int(v)) for m in banks for l in m for b in l for v in b)
if peak > 32767:
    raise SystemExit(f'Bank overshoot: {peak}')
lines = ['// Generated by tools/generate_tables.py. Original analytic waveforms.',
         '#pragma once', '#include <opxy/types.hpp>', 'namespace vader {',
         'const opxy::i16 waves[4][9][5][513] = {']
for mode in banks:
    lines.append('{')
    for level in mode:
        lines.append('{')
        for band in level:
            lines.append('{' + ','.join(map(str, band)) + '},')
        lines.append('},')
    lines.append('},')
lines.extend(['};', '}'])
(root / 'tables.hpp').write_text('\n'.join(lines) + '\n')
lines = ['// Generated by tools/generate_tables.py.', '#pragma once', '#include <opxy/types.hpp>', 'namespace vader {']
for name, values in (
    ('pitch_ratios', [round(65536 * 2 ** (4 * i / 64)) for i in range(65)]),
    ('fall_coefficients', [round((2**31 - 1) * np.exp(-1 / (44100 * 0.005 * 32 ** (i / 64)))) for i in range(65)]),
    ('fall_milliseconds', [round(5 * 32 ** (i / 64) * 1000) for i in range(65)]),
):
    lines.append(f'const opxy::u32 {name}[65] = {{' + ','.join(map(str, values)) + '};')
lines.append('}')
(root / 'control_tables.hpp').write_text('\n'.join(lines) + '\n')
print(f'Generated band-limited banks; peak {peak}/32768.')
